/**
 * The benchmark matrix and how its results are written up (#194).
 */
import { PROFILES, type Scenario, type ScenarioResult } from './relaySim';
import type { CodecCost } from './measureCodec';

const base = { clicks: 30, durationMs: 120_000, seed: 20261019 } as const;
/** A 360 KB page of history every 2 s: the transfer a command has to get past. */
export const BURST = { everyMs: 2_000, kb: 360 } as const;

const label = (s: Omit<Scenario, 'name'>) =>
  `${s.profile.name} · ${s.sessions} sessions · ${s.conversation} · ${s.mode}${s.dropAtMs ? ' · drop' : ''}${s.burst ? ' · burst' : ''}${s.fifo ? ' · fifo' : ''}`;

export function scenario(s: Omit<Scenario, 'name'>): Scenario {
  return { ...s, name: label(s) };
}

/** Every combination the issue names: 1/5/20 sessions, small/large, idle/background, latency and loss, a drop, and a burst. */
export function matrix(): Scenario[] {
  const out: Scenario[] = [];
  for (const [transport, profile] of [
    ['lan', PROFILES.lan],
    ['relay', PROFILES.relayGood],
    ['relay', PROFILES.relayPoor],
  ] as const) {
    for (const sessions of [1, 5, 20] as const) {
      for (const conversation of ['small', 'large'] as const) out.push(scenario({ ...base, transport, profile, sessions, conversation, mode: 'active' }));
    }
    out.push(scenario({ ...base, transport, profile, sessions: 20, conversation: 'large', mode: 'idle' }));
    out.push(scenario({ ...base, transport, profile, sessions: 20, conversation: 'large', mode: 'background' }));
    if (transport === 'relay') out.push(scenario({ ...base, transport, profile, sessions: 5, conversation: 'large', mode: 'active', dropAtMs: 60_000 }));
    out.push(scenario({ ...base, transport, profile, sessions: 5, conversation: 'large', mode: 'active', burst: BURST }));
    if (transport === 'relay') out.push(scenario({ ...base, transport, profile, sessions: 5, conversation: 'large', mode: 'active', burst: BURST, fifo: true }));
  }
  return out;
}

const ms = (n: number) => (n >= 100 ? `${Math.round(n)}` : n.toFixed(1));
const kb = (n: number) => `${Math.round(n / 1024)}`;
const pair = (p: { p50: number; p95: number }) => `${ms(p.p50)} / ${ms(p.p95)}`;

export function renderReport(results: readonly ScenarioResult[], codec: readonly CodecCost[]): string {
  const rows = results.map((r) => {
    const s = r.scenario;
    return `| ${s.name} | ${r.clicks} | ${pair(r.recvMs)} | ${pair(r.firstMs)} | ${pair(r.interactiveMs)} | ${pair(r.commandMs)} | ${ms(r.daemonMs.p50)} | ${r.queueMs ? ms(r.queueMs.p50) : '–'} | ${r.sendAckMs ? ms(r.sendAckMs.p50) : '–'} | ${ms(r.renderMs.p50)} | ${kb(r.bytesDown)} | ${r.messagesDown} | ${r.snapshotsSent}/${r.snapshotsBuilt} | ${r.reconnects} |`;
  });
  return `# Remote relay benchmark results

Generated by \`npm run bench:relay\` (#194). Method, model and gates: \`docs/relay-benchmark.md\`.
Virtual time and a seeded generator, so a run is the same on every machine. Times are milliseconds,
p50 / p95. Each scenario is a ${Math.round((results[0]?.scenario.durationMs ?? 0) / 1000)} s run with
${results[0]?.scenario.clicks ?? 0} row clicks and 30 commands.

**What is measured and what is modelled.** The daemon's queueing, lanes, snapshot coalescing, conversation
window and tracing, and the page's click timing, are the real code. The network (a part is acknowledged,
and arrives, after twice the one-way time to Supabase), the daemon's \`source.init\` time, and the browser's
decode and render time are models with the constants in \`test/bench/relaySim.ts\`. Real browser numbers
come from the click trace in the daemon log (\`trace:\` lines, #190), not from here.

| Scenario | Clicks done | click→recv | click→first | click→interactive | Command→ack | Daemon p50 | Queue p50 | Send+ack p50 | Render p50 | KB down | Parts down | Snapshots sent/built | Reconnects |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Codec cost (real time, this machine)

Left out of the model's clock on purpose (see the method). Seal runs on the daemon, open in the browser.

| Payload KB | Parts | Seal ms | Open ms |
|---|---|---|---|
${codec.map((c) => `| ${c.kb} | ${c.parts} | ${c.sealMs} | ${c.openMs} |`).join('\n')}
`;
}
